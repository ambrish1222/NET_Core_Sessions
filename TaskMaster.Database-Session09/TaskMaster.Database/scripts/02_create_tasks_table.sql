/* =====================================================================
   Session 9 | Slides 5, 7, 8 | Create the Tasks table (+ Primary Key)

   Status codes   : 1 = Pending, 2 = InProgress, 3 = Completed
   Priority codes : 1 = Low,     2 = Medium,     3 = High
   (Slide 18 turns the status codes into a real lookup table.)
   ===================================================================== */
USE TaskDb;
GO

IF OBJECT_ID(N'dbo.Tasks', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.Tasks
    (
        Id        INT IDENTITY(1,1) PRIMARY KEY,   -- unique row id, generated by SQL Server
        Title     NVARCHAR(200) NOT NULL,          -- required
        Status    INT           NOT NULL,
        Priority  INT           NOT NULL,
        DueDate   DATETIME2     NULL,              -- optional: NULL = "no due date"
        CreatedAt DATETIME2     NOT NULL           -- required (a DEFAULT is added in script 07)
    );
END
GO

-- Inspect the table definition: one row per column
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = N'dbo' AND TABLE_NAME = N'Tasks'
ORDER BY ORDINAL_POSITION;
GO
